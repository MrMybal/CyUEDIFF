inline std::vector<std::uint8_t> fixture_hex(const char *text) {
    auto nibble = [](char c) { return c <= '9' ? c - '0' : c - 'a' + 10; };
    std::vector<std::uint8_t> bytes;
    while (*text) {
        bytes.push_back(static_cast<std::uint8_t>(nibble(text[0]) * 16 + nibble(text[1])));
        text += 2;
    }
    return bytes;
}
